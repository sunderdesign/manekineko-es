在现代西方人的眼中，这可能令人惊讶，但在明治时代之前的日本民间神道教中，这些物品绝对没有任何淫秽或下流的含义。在一个生存依赖于丰收和家族血脉延续的农业社会中，生物学上的生育能力和经济上的富足被理解为同一种生命力（*结*）的表达。

![带有注连绳和木制护身符的传统日本店铺神龛](/images/historia-konsei-shimenawa.jpeg)

